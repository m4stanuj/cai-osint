from html import escape
from pathlib import Path
import re
from typing import Dict, Any


def _inline(value: Any) -> str:
    """Keep observation text in one Markdown field."""
    single_line = " ".join(str(value).split())
    return re.sub(r"([\\`*_\[\]#|])", r"\\\1", escape(single_line, quote=False))

def generate_markdown_report(data: Dict[str, Any], output_path: str = None) -> str:
    target = _inline(data.get("target", "Unknown"))
    raw_score = data.get("security_score")
    score = f"{raw_score} / 10.0" if isinstance(raw_score, (int, float)) and 0 <= raw_score <= 10 else "Not provided"
    posture = _inline(data.get("posture", "UNKNOWN"))
    findings = data.get("findings", [])
    services = data.get("open_services", [])
    timestamp = _inline(data.get("scan_timestamp", "Not provided"))

    md = f"""# 🛡️ Executive Security Assessment Report: {target}

**Generated by:** `cai-osint` Autonomous AI Security Auditor  
**Audit Timestamp:** {timestamp}
**Overall Posture:** {posture}
**Security Score:** {score}

---

## 📊 Executive Summary

| Target Host | Security Score | Posture Rating | Critical Issues | Total Open Ports |
| :--- | :--- | :--- | :--- | :--- |
| **{target}** | **{score}** | **{posture}** | **{len([f for f in findings if f.get('severity') == 'CRITICAL'])}** | **{len(services)}** |

---

## 🚨 Security Findings & Vulnerabilities

"""
    if not findings:
        md += "No findings were supplied in the collected evidence. Coverage may be incomplete.\n\n"
    else:
        for f in findings:
            severity = _inline(f.get("severity", "Unspecified"))
            md += f"""### {severity} - {_inline(f.get('title', 'Untitled finding'))}
* **Description:** {_inline(f.get('desc', 'Not provided'))}
* **Remediation Action:** {_inline(f.get('remediation', 'Review the finding'))}

"""

    md += """---

## 🌐 Exposed Services & Open Ports

| Port | State | Identified Service | Service Banner |
| :--- | :--- | :--- | :--- |
"""
    if not services:
        md += "| - | Unreported | No service observations supplied | - |\n"
    else:
        for s in services:
            cells = [_inline(s.get(field, "Unreported")) for field in ("port", "state", "service", "banner")]
            md += "| " + " | ".join(cells) + " |\n"

    md += f"""
---

## 🔒 Actionable Remediation Checklist
- [ ] Review all open ports against company egress/ingress security policies.
- [ ] Ensure strict TLS 1.3 enforcement on port 443 with automated cert renewal.
- [ ] Place internal management and database ports behind a VPN or zero-trust tunnel.

*Report signed by `cai-osint` Engine (M4ST Ecosystem).*
"""

    if output_path:
        path = Path(output_path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(md, encoding="utf-8")

    return md
